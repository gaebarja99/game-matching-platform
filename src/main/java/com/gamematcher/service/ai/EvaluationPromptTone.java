package com.gamematcher.service.ai;

/**
 * LLM 매치 평가 프롬프트에 붙이는 톤·분량 균형 지침.
 * 고성과 경기에서 칭찬보다 충고가 과도해지는 현상을 줄이기 위함.
 */
public final class EvaluationPromptTone {

    private EvaluationPromptTone() {
    }

    /**
     * 모든 게임 공통: 데이터를 보고 상대적 수준을 판단할 때의 균형 규칙.
     */
    public static String commonBalanceSection() {
        return """

                [톤·분량 균형 — 반드시 준수]
                1. 경기 데이터상 플레이가 전반적으로 우수하면(승리·높은 기여·핵심 지표가 기대 이상), 칭찬과 구체적 강점이 코멘트의 주축이어야 합니다.
                   - summary: 먼저 잘한 점을 분명히 인정한 뒤, 보완점이 있으면 짧게 덧붙이십시오. '잘했지만 부족하다'만 길게 쓰지 마십시오.
                   - detailedComment: [강점]의 분량(문장 수·글자 수 체감)이 [약점]과 [개선안]을 합한 것보다 짧아지지 않게 하십시오. 우수한 경기에서는 강점이 대략 절반 이상을 차지하는 것이 목표입니다.
                   - [약점]은 데이터에 근거한 한두 가지로 제한하고, 전체 평가를 흐리는 과장 비판·같은 말 반복은 금지입니다.
                   - [개선안]은 '정상에서 한 단계 성장' 수준으로 짧게(우수한 경기에서는 총 1~3문장); 나열식·장문 충고로 채우지 마십시오.
                2. 경기가 평범하거나 아쉬운 경우에는 강점·약점·개선을 균형 있게 작성합니다.
                3. 경기가 매우 부진하면 개선과 원인 분석 비중을 늘려도 됩니다. 다만 무례하거나 인신공격적인 표현은 금지입니다.
                """;
    }

    /**
     * 시스템이 미리 산출한 기여도 점수가 있을 때(예: 발로란트) 등급 구간별 톤을 고정합니다.
     * 점수·등급 명칭은 응답 본문에 쓰지 않도록 지시합니다.
     *
     * @param contributionScore {@code null}이면 빈 문자열
     */
    public static String scoreTierHint(Integer contributionScore) {
        if (contributionScore == null) {
            return "";
        }
        int s = contributionScore;
        if (s >= 120) {
            return """

                    [내부 참고: 이 플레이어의 시스템 기여도는 상위 구간입니다.]
                    - 반드시: 칭찬·[강점] 서술을 가장 두껍게.[약점]은 한 문장 이내로 매우 짧게.[개선안]은 총 1~2문장(또는 짧은 팁 2개 이내)로 제한하십시오.
                    - 금지: 높은 기여에도 불구하고 충고·단점이 대부분을 차지하는 구성.
                    - 응답에 점수·등급·랭크 명칭을 직접 쓰지 마십시오.
                    """;
        }
        if (s >= 90) {
            return """

                    [내부 참고: 이 플레이어의 시스템 기여도는 중상위 구간입니다.]
                    - [강점]이 [약점]+[개선안]보다 짧아지지 않게 하십시오. 개선안을 길게 늘리지 마십시오.
                    - 응답에 점수·등급·랭크 명칭을 직접 쓰지 마십시오.
                    """;
        }
        return """

                [내부 참고: 이 플레이어의 시스템 기여도는 이 경기에서 상대적으로 낮은 편으로 볼 수 있습니다.]
                - 약점과 구체적 개선안을 충분히 제시해도 됩니다.
                - 응답에 점수·등급·랭크 명칭을 직접 쓰지 마십시오.
                """;
    }
}
